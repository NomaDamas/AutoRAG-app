#!/usr/bin/env node
/**
 * Regenerates src/main/conversion-aliases.ts from the real `filee-cli`.
 *
 * Filee spells one format several ways (`jpg`, `jpeg`, `jpe`, `jfif`; `html`,
 * `htm`). The librarian's route matrix lists only the first spelling, so the
 * rename-to-convert planner needs the other spellings to treat `photo.jpeg`
 * and `photo.jpg` as the same format. `filee formats <ext>` prints the
 * canonical id and every alias on its first line; this script reads that line
 * for every source format the matrix knows.
 *
 *   bun scripts/gen-conversion-aliases.mjs            # filee-cli on PATH
 *   FILEE_CLI=/path/to/filee-cli bun scripts/gen-conversion-aliases.mjs
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SOURCE_FAMILIES } from "@autorag/librarian";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const filee = process.env.FILEE_CLI ?? "filee-cli";
const target = join(root, "src", "main", "conversion-aliases.ts");
const members = new Set(Object.values(SOURCE_FAMILIES).flat());
const aliases = new Map();
for (const member of members) {
	const first = execFileSync(filee, ["formats", member], { encoding: "utf8" }).split("\n")[0] ?? "";
	const match = /^.*? \(([^)]*)\) converts to:/.exec(first);
	if (match === null) throw new Error(`Unexpected \`filee formats ${member}\` output: ${first}`);
	for (const id of match[1].split(",").map((spelling) => spelling.trim())) {
		// Dotted ids (`tar.gz`) never occur as the last extension of a file name; a
		// spelling the matrix lists itself is its own format, never an alias.
		if (id === member || id.includes(".") || members.has(id)) continue;
		if (aliases.has(id) && aliases.get(id) !== member) throw new Error(`${id} is an alias of both ${aliases.get(id)} and ${member}`);
		aliases.set(id, member);
	}
}

const rows = [...aliases].sort(([a], [b]) => a.localeCompare(b)).map(([alias, canonical]) => `\t${JSON.stringify(alias)}: ${JSON.stringify(canonical)},`);
const source = `// Generated by scripts/gen-conversion-aliases.mjs from \`filee formats <ext>\`. Do not edit by hand.

/** Other spellings Filee accepts for a format id, mapped to the id the route matrix uses. */
export const FILEE_FORMAT_ALIASES: Readonly<Record<string, string>> = {
${rows.join("\n")}
};
`;
writeFileSync(target, source);
console.log(`wrote ${aliases.size} aliases to ${target}`);
