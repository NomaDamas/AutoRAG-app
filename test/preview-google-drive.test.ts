describe("PreviewDocument.thumbnail", () => {
	const base = { name: "a.gdoc", path: "/a.gdoc", ext: "gdoc", size: 1, modifiedAt: "2026-01-01T00:00:00.000Z", mime: "application/json", truncated: false, bytes: null, pages: null, office: null, slidesRendering: false };

	it("is an autorag-thumb URL or null, and is required", () => {
		expect(isPreviewDocument({ ...base, thumbnail: null })).toBe(true);
		expect(isPreviewDocument({ ...base, thumbnail: "autorag-thumb://local/?path=a.gdoc&mtime=1&size=640" })).toBe(true);
		expect(isPreviewDocument({ ...base, thumbnail: 3 })).toBe(false);
		expect(isPreviewDocument(base)).toBe(false);
	});
});

describe("driveThumbnail", () => {
	const target = { path: "/drive/Plan.gdoc", ext: "gdoc", mtimeMs: 5 };

	it("is null for a file that is not a Drive pointer, without asking the OS", async () => {
		let asked = 0;
		const icons = { cachedPreview: () => null, preview: async () => (asked += 1, "autorag-thumb://x") };
		expect(await driveThumbnail({ ...target, ext: "docx" }, icons, 50)).toBeNull();
		expect(asked).toBe(0);
	});

	it("uses the thumbnail an earlier selection cached, with no new generation", async () => {
		let generated = 0;
		const icons = { cachedPreview: () => "autorag-thumb://cached", preview: async () => (generated += 1, "autorag-thumb://fresh") };
		expect(await driveThumbnail(target, icons, 50)).toBe("autorag-thumb://cached");
		expect(generated).toBe(0);
	});

	it("generates the thumbnail when none is cached", async () => {
		const icons = { cachedPreview: () => null, preview: async () => "autorag-thumb://fresh" };
		expect(await driveThumbnail(target, icons, 50)).toBe("autorag-thumb://fresh");
	});

	it("gives up after the budget so Space never waits on a slow provider, and lets the generation finish for next time", async () => {
		const slow = Promise.withResolvers<string | null>();
		const icons = { cachedPreview: () => null, preview: () => slow.promise };
		const started = Date.now();
		expect(await driveThumbnail(target, icons, 20)).toBeNull();
		expect(Date.now() - started).toBeLessThan(1000);
		slow.resolve("autorag-thumb://late");
	});

	it("is null when the provider fails or has no source", async () => {
		const failing = { cachedPreview: () => null, preview: async (): Promise<string | null> => { throw new Error("xpc"); } };
		expect(await driveThumbnail(target, failing, 50)).toBeNull();
		expect(await driveThumbnail(target, null, 50)).toBeNull();
	});

	it("opens native-only documents immediately and publishes their thumbnail when the OS finishes", async () => {
		const targetPict = { path: "/docs/Picture.pict", ext: "pict", mtimeMs: 5 };
		const cached = { cachedPreview: () => "autorag-thumb://cached", preview: async () => "autorag-thumb://fresh" };
		expect(nativeThumbnail(targetPict, cached, () => undefined)).toBe("autorag-thumb://cached");
		const slow = Promise.withResolvers<string | null>();
		const published: string[] = [];
		expect(nativeThumbnail(targetPict, { cachedPreview: () => null, preview: () => slow.promise }, (url) => published.push(url))).toBeNull();
		expect(published).toEqual([]);
		slow.resolve("autorag-thumb://late");
		await slow.promise;
		await Promise.resolve();
		expect(published).toEqual(["autorag-thumb://late"]);
	});
});
