interface IconProps {
	readonly name: string;
	readonly size?: number;
	readonly className?: string;
	readonly strokeWidth?: number;
}

/** The prototype's `icon(name, size=15, cls='')`: a single stroked glyph. */
export function Icon({ name, size = 15, className, strokeWidth = 1.8 }: IconProps): ReactElement | null {
	const Glyph = ICONS[name];
	if (Glyph === undefined) {
		return null;
	}
	return <Glyph size={size} strokeWidth={strokeWidth} className={className} aria-hidden="true" />;
}

